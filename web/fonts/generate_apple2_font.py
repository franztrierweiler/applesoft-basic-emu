# Font metrics (in font units, upem=800)
UPEM = 800
PIXEL = UPEM // 8  # 100 units per pixel
GLYPH_WIDTH = 7 * PIXEL  # 700
ADVANCE = 8 * PIXEL  # 800
ASCENT = 7 * PIXEL  # 700
DESCENT = -1 * PIXEL  # -100 (for descenders like g, j, p, q, y)


def bitmap_to_drawing(pen, bitmap: list[int]) -> None:
    """Convert an 8-row bitmap to pen drawing commands (filled rectangles)."""
    for row_idx, row_byte in enumerate(bitmap):
        y_top = (7 - row_idx) * PIXEL
        y_bottom = y_top - PIXEL
        for col in range(7):
            # Bit 0 = rightmost pixel, so we check from bit 5 down to bit 0
            # Actually for Apple II: bit layout varies. We use a 6-bit field.
            # Bit 5 = leftmost, bit 0 = rightmost for the 6 significant bits
            if row_byte & (1 << (5 - col)):
                x_left = (col + 1) * PIXEL  # offset by 1 pixel for centering
                x_right = x_left + PIXEL
                # Draw a filled rectangle (clockwise)
                pen.moveTo((x_left, y_bottom))
                pen.lineTo((x_left, y_top))
                pen.lineTo((x_right, y_top))
                pen.lineTo((x_right, y_bottom))
                pen.closePath()


def generate_font() -> None:
    """Generate the Apple II TTF font using FontBuilder.setupGlyf."""
    # Build glyph names and character map
    glyph_names = [".notdef"]
    cmap = {}
    glyph_bitmaps = {}

    for codepoint in range(0x20, 0x7F):
        name = f"char{codepoint:04X}"
        glyph_names.append(name)
        cmap[codepoint] = name
        glyph_bitmaps[name] = APPLE2_CHARS.get(codepoint, [0] * 8)

    fb = FontBuilder(UPEM, isTTF=True)
    fb.setupGlyphOrder(glyph_names)
    fb.setupCharacterMap(cmap)

    # Build glyph drawings as pen-compatible dict
    pen_drawings = {}
    for name in glyph_names:
        if name == ".notdef":
            # Notdef: hollow rectangle
            pen_drawings[name] = {
                "numberOfContours": 2,
                "coordinates": [
                    (0, 0), (ADVANCE, 0), (ADVANCE, ASCENT), (0, ASCENT),
                    (PIXEL, PIXEL), (PIXEL, ASCENT - PIXEL),
                    (ADVANCE - PIXEL, ASCENT - PIXEL), (ADVANCE - PIXEL, PIXEL),
                ],
                "flags": [1] * 8,
                "components": None,
            }
        else:
            bitmap = glyph_bitmaps[name]
            coords = []
            end_pts = []
            flags = []
            for row_idx, row_byte in enumerate(bitmap):
                y_top = (7 - row_idx) * PIXEL
                y_bot = y_top - PIXEL
                for col in range(6):
                    if row_byte & (1 << col):
                        x_left = (col + 1) * PIXEL
                        x_right = x_left + PIXEL
                        base = len(coords)
                        coords.extend([
                            (x_left, y_bot),
                            (x_right, y_bot),
                            (x_right, y_top),
                            (x_left, y_top),
                        ])
                        flags.extend([1, 1, 1, 1])
                        end_pts.append(base + 3)
            pen_drawings[name] = (coords, end_pts, flags)

    # Use setupGlyf with pen approach
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    glyph_table = {}
    for name in glyph_names:
        pen = TTGlyphPen(None)
        if name == ".notdef":
            # Outer rectangle
            pen.moveTo((0, 0))
            pen.lineTo((0, ASCENT))
            pen.lineTo((ADVANCE, ASCENT))
            pen.lineTo((ADVANCE, 0))
            pen.closePath()
            # Inner rectangle (hole)
            pen.moveTo((PIXEL, PIXEL))
            pen.lineTo((ADVANCE - PIXEL, PIXEL))
            pen.lineTo((ADVANCE - PIXEL, ASCENT - PIXEL))
            pen.lineTo((PIXEL, ASCENT - PIXEL))
            pen.closePath()
        else:
            bitmap = glyph_bitmaps[name]
            for row_idx, row_byte in enumerate(bitmap):
                y_top = (7 - row_idx) * PIXEL
                y_bot = y_top - PIXEL
                for col in range(6):
                    if row_byte & (1 << col):
                        x_left = (col + 1) * PIXEL
                        x_right = x_left + PIXEL
                        pen.moveTo((x_left, y_bot))
                        pen.lineTo((x_left, y_top))
                        pen.lineTo((x_right, y_top))
                        pen.lineTo((x_right, y_bot))
                        pen.closePath()
        glyph_table[name] = pen.glyph()

    fb.setupGlyf(glyph_table)

    # Corriger automatiquement le sens des contours
    from fontTools.ttLib.tables._g_l_y_f import Glyph
    glyf_table = fb.font["glyf"]
    for name in glyph_names:
        glyph = glyf_table[name]
        if glyph.numberOfContours > 0:
            glyph.recalcBounds(glyf_table)

    # Set metrics
    metrics = {}
    for name in glyph_names:
        metrics[name] = (ADVANCE, 0)
    fb.setupHorizontalMetrics(metrics)

    fb.setupHorizontalHeader(ascent=ASCENT, descent=DESCENT)

    fb.setupNameTable({
        "familyName": "Apple II",
        "styleName": "Regular",
    })

    fb.setupOS2(
        sTypoAscender=ASCENT,
        sTypoDescender=DESCENT,
        sTypoLineGap=0,
        usWinAscent=ASCENT,
        usWinDescent=abs(DESCENT),
        sxHeight=ASCENT // 2,
        sCapHeight=ASCENT,
    )

    fb.setupPost()

    font = fb.font

    # Save as TTF
    out_dir = os.path.dirname(os.path.abspath(__file__))
    ttf_path = os.path.join(out_dir, "apple2.ttf")
    font.save(ttf_path)
    print(f"TTF saved: {ttf_path} ({os.path.getsize(ttf_path)} bytes)")

    # Convert to WOFF2
    font.flavor = "woff2"
    woff2_path = os.path.join(out_dir, "apple2.woff2")
    font.save(woff2_path)
    print(f"WOFF2 saved: {woff2_path} ({os.path.getsize(woff2_path)} bytes)")


if __name__ == "__main__":
    generate_font()
